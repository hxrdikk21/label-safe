def curated_medications() -> list[CuratedMedication]:
    items: list[CuratedMedication] = []
    for category, names in NARROW_THERAPEUTIC_INDEX.items():
        items.extend(CuratedMedication(n, category, is_narrow_therapeutic_index=True) for n in names)
    for category, names in THERAPEUTIC_AREAS.items():
        items.extend(CuratedMedication(n, category) for n in names)
    return items


async def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1] if __doc__ else None)
    parser.add_argument("--output", type=Path, default=DEFAULT_CATALOG_PATH)
    args = parser.parse_args()
    async with httpx.AsyncClient(timeout=30.0, headers={"User-Agent": "LabelSafe seed builder"}) as http:
        normalizer = MedicationNormalizer(RxNavClient(http), allow_approximate=False)
        catalog, skipped = await build_catalog(
            curated_medications(), normalizer, catalog_version=CATALOG_VERSION
        )
    args.output.write_text(
        json.dumps(catalog.model_dump(mode="json"), indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    for line in skipped:
        print(f"skipped: {line}", file=sys.stderr)
    print(f"wrote {len(catalog.concepts)} concepts to {args.output} (catalog hash {catalog.catalog_hash()})")
    return 0


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
